# -*- coding: utf-8 -*-
"""重写 SessionUsageView：单会话用量统计 UI，参照主面板设计语言。
合成「会话级 days」后直接复用主面板 Trend / Donut 组件；概览卡用大号数值样式。"""
import io, sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
P = r"E:\WorkSpace\Projects\dsh\dsh-token-panel\build\body.js"
lines = io.open(P, encoding="utf-8", newline="").read().split("\n")

start = next(i for i, l in enumerate(lines) if "function SessionUsageView({ sessionId }) {" in l)
end = start
while end < len(lines) and lines[end] != "\t\t}":
    end += 1
# end 现在指向函数收尾的 "\t\t}"

T = "\t\t"
new = [
    T + '// 对话区「用量」tab：单会话用量统计，参照主面板「今天」视图的设计语言。',
    T + "// 数据：/api/usage-stats 的按天会话桶（days[].sessions）本地聚合出该会话，",
    T + "// 再映射成合成 days 喂给主面板的 Trend / Donut——同源同款，零重复绘制代码。",
    T + "function SessionUsageView({ sessionId }) {",
    T + "\tconst [data, setData] = react.useState(null);",
    T + "\tconst [error, setError] = react.useState(null);",
    T + "\tconst [busy, setBusy] = react.useState(false);",
    T + "\treact.useEffect(() => {",
    T + "\t\tif (!sessionId) return;",
    T + "\t\tlet cancelled = false;",
    T + "\t\tconst load = async (force) => {",
    T + "\t\t\ttry {",
    T + '\t\t\t\tconst res = await fetch("/api/usage-stats" + (force ? "?refresh=1" : ""), { credentials: "same-origin" });',
    T + '\t\t\t\tif (!res.ok) throw new Error("HTTP " + res.status);',
    T + "\t\t\t\tconst json = await res.json();",
    T + '\t\t\t\tif (!json || json.ok === false) throw new Error((json && json.error) || "响应异常");',
    T + "\t\t\t\tif (!cancelled) { setData(json); setError(null); }",
    T + "\t\t\t} catch (e) {",
    T + "\t\t\t\tif (!cancelled) setError(String((e && e.message) || e));",
    T + "\t\t\t}",
    T + "\t\t};",
    T + "\t\t// 两拍：先缓存秒开，再强扫拿当前会话的最新增量（新会话不在旧缓存里）",
    T + "\t\tload(false).then(() => load(true));",
    T + "\t\treturn () => { cancelled = true; };",
    T + "\t}, [sessionId]);",
    T + "\tif (!sessionId) return element(\"div\", { className: \"ust-placeholder\" }, \"打开一个会话后查看用量\");",
    T + "\tconst days = (data && data.days) || [];",
    T + "\t// 该会话的按天用量 → 合成 days（与主面板组件同构），Trend / Donut 直接复用",
    T + "\tconst sessionDays = days.map((d) => {",
    T + "\t\tconst s = (d.sessions || []).find((x) => x.id === sessionId);",
    T + "\t\treturn {",
    T + "\t\t\tdate: d.date,",
    T + "\t\t\ttotal: s ? s.total || 0 : 0,",
    T + "\t\t\tturns: s ? s.turns || 0 : 0,",
    T + "\t\t\tmessages: s ? s.messages || 0 : 0,",
    T + "\t\t\tdurationMs: s ? s.durationMs || 0 : 0,",
    T + "\t\t\tbyModel: s ? (s.byModel || []) : [],",
    T + "\t\t\tsessions: [], providers: [],",
    T + "\t\t};",
    T + "\t});",
    T + "\tconst active = sessionDays.filter((d) => d.total > 0);",
    T + "\tconst agg = active.reduce((a, d) => ({",
    T + "\t\ttotal: a.total + d.total,",
    T + "\t\tturns: a.turns + d.turns,",
    T + "\t\tmessages: a.messages + d.messages,",
    T + "\t\tdurationMs: a.durationMs + d.durationMs,",
    T + "\t}), { total: 0, turns: 0, messages: 0, durationMs: 0 });",
    T + "\tconst byModel = {};",
    T + "\tactive.forEach((d) => (d.byModel || []).forEach((m) => {",
    T + "\t\tconst bm = byModel[m.model] || { model: m.model, color: m.color, input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 };",
    T + "\t\tbm.input += m.input || 0; bm.output += m.output || 0;",
    T + "\t\tbm.cacheRead += m.cacheRead || 0; bm.cacheWrite += m.cacheWrite || 0;",
    T + "\t\tbm.total += m.total || 0;",
    T + "\t\tif (!bm.color && m.color) bm.color = m.color;",
    T + "\t\tbyModel[m.model] = bm;",
    T + "\t}));",
    T + "\tconst allMetrics = sumMetrics(Object.values(byModel));",
    T + "\tconst todayKey = dateKey(Date.now());",
    T + "\tconst todayAgg = sessionDays.find((d) => d.date === todayKey) || { total: 0, turns: 0, messages: 0, durationMs: 0, byModel: [] };",
    T + "\tconst todaySum = sumMetrics(todayAgg.byModel || []);",
    T + "\tconst metricCard = (label, value, sub) => element(\"div\", { key: label, className: \"ust-metric\" },",
    T + "\t\telement(\"div\", { className: \"ust-metric-label\" }, element(\"span\", null, label)),",
    T + "\t\telement(\"div\", { className: \"ust-metric-value\" }, value),",
    T + "\t\telement(\"div\", { className: \"ust-metric-sub\" }, sub));",
    T + '\tconst cards = (title, cards_) => element("div", { key: title },',
    T + '\t\telement("div", { className: "ust-sub", style: { fontWeight: 650, color: "var(--ink)", marginBottom: 8 } }, title),',
    T + "\t\telement(\"div\", { className: \"ust-metrics\" }, cards_));",
    T + '\tconst refresh = () => { setBusy(true); fetch("/api/usage-stats?refresh=1", { credentials: "same-origin" }).then((r) => r.json()).then((j) => { if (j && j.ok) setData(j); }).catch(() => {}).finally(() => setBusy(false)); };',
    T + '\tconst wnd = { id: "all", label: "全部", dateKeys: sessionDays.map((d) => d.date) };',
    T + '\treturn element("div", { className: "ust-root ust-sessview" },',
    T + '\t\telement("div", { className: "ust-block-head" },',
    T + '\t\t\telement("div", { className: "ust-block-titleRow" },',
    T + '\t\t\t\telement("h2", { className: "ust-h2" }, "会话用量"),',
    T + '\t\t\t\telement("div", { className: "ust-sub" }, data ? "数据更新于 " + fmtClock(data.generatedAt) : "读取中…"),',
    T + "\t\t\t),",
    T + '\t\t\telement("button", { type: "button", className: "ust-btn ust-btn--ghost", disabled: busy, onClick: refresh }, busy ? "刷新中…" : "刷新"),',
    T + "\t\t),",
    T + '\t\terror ? element("div", { className: "ust-warn" }, "加载失败：" + error) : null,',
    T + '\t\tcards("今天", [',
    T + '\t\t\tmetricCard("Token 用量", fmtLarge(todayAgg.total), "TOKENS"),',
    T + '\t\t\tmetricCard("轮次", String(todayAgg.turns || 0), "对话轮次"),',
    T + '\t\t\tmetricCard("消息", String(todayAgg.messages || 0), "条"),',
    T + '\t\t\tmetricCard("活跃时长", fmtDuration(todayAgg.durationMs || 0), "分段活跃口径"),',
    T + '\t\t\tmetricCard("缓存命中", fmtLarge(todaySum.cacheRead), "TOKENS"),',
    T + '\t\t\tmetricCard("命中率", fmtPct(hitRateOf(todaySum)), "缓存命中 / 当期满量"),',
    T + "\t\t]),",
    T + '\t\tcards("全部历史", [',
    T + '\t\t\tmetricCard("Token 用量", fmtLarge(agg.total), "TOKENS"),',
    T + "\t\t\tmetricCard(\"轮次\", String(agg.turns || 0), \"对话轮次\"),",
    T + "\t\t\tmetricCard(\"消息\", fmtFull(agg.messages), \"条\"),",
    T + "\t\t\tmetricCard(\"活跃时长\", fmtDuration(agg.durationMs || 0), \"分段活跃口径\"),",
    T + "\t\t\tmetricCard(\"缓存命中\", fmtLarge(allMetrics.cacheRead), \"TOKENS\"),",
    T + "\t\t\tmetricCard(\"命中率\", fmtPct(hitRateOf(allMetrics)), \"缓存命中 / 当期满量\"),",
    T + "\t\t\tmetricCard(\"活跃天数\", String(active.length) + \" 天\", \"有用量的天数\"),",
    T + "\t\t]),",
    T + "\t\tactive.length > 0 ? element(Trend, { days: sessionDays, window: wnd }) : null,",
    T + "\t\tactive.length > 0 ? element(Donut, { days: sessionDays, window: wnd }) : null,",
    T + "\t\tactive.length === 0 && data ? element(\"div\", { className: \"ust-placeholder\" }, \"本会话尚无 Token 用量记录\") : null,",
    T + "\t);",
    T + "}",
]
lines[start:end + 1] = new
io.open(P, "w", encoding="utf-8", newline="").write("\n".join(lines))
print("SessionUsageView rewritten: lines", start + 1, "-", end + 1, "->", len(new), "lines")
